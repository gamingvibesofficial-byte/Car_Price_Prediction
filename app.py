import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

# ---------------- PAGE SETTINGS ----------------
st.set_page_config(
    page_title="CarValue | Car Price Predictor",
    page_icon="🚗",
    layout="wide"
)

# ---------------- LOAD MODEL ----------------
@st.cache_resource
def load_model():
    model_path = Path(__file__).parent / "car_price_model.pkl"
    return joblib.load(model_path)

try:
    model = load_model()
except Exception as e:
    st.error("The prediction model could not be loaded.")
    st.exception(e)
    st.stop()

# ---------------- CUSTOM DESIGN ----------------
st.markdown("""
<style>
    .stApp {background: linear-gradient(135deg, #f7f9fc 0%, #eef3fb 100%);}
    .block-container {padding-top: 2rem; padding-bottom: 3rem; max-width: 1150px;}
    .hero {
        padding: 2rem 2.2rem; border-radius: 22px;
        background: linear-gradient(115deg, #101b35, #244b83);
        color: white; margin-bottom: 1.5rem;
    }
    .hero h1 {color: white; font-size: 2.5rem; margin-bottom: .4rem;}
    .hero p {color: #dce8fb; font-size: 1.05rem; margin-bottom: 0;}
    .result {
        background: white; border: 1px solid #dce5f2;
        padding: 1.5rem; border-radius: 18px; text-align: center;
        box-shadow: 0 8px 24px rgba(25,45,80,.07);
    }
    .result-label {color: #52627a; font-size: .95rem;}
    .result-price {color: #123d75; font-size: 2.3rem; font-weight: 800;}
    div.stButton > button {
        background: #174b8b; color: white; border: 0;
        border-radius: 10px; padding: .65rem 1.2rem; font-weight: 700;
        width: 100%;
    }
    div.stButton > button:hover {background: #0e3566; color: white;}
</style>
""", unsafe_allow_html=True)

# ---------------- HEADER ----------------
st.markdown("""
<div class="hero">
  <h1>🚗 CarValue</h1>
  <p>Smart used-car price estimation powered by Machine Learning</p>
</div>
""", unsafe_allow_html=True)

st.write("Enter the details of your car below to get an estimated resale price.")
st.caption("This estimate is generated by your trained Random Forest model. Actual market prices may vary.")

# These choices match the categories in the supplied car_data.csv dataset.
car_names = [
    "Maruti Wagon R", "Toyota Innova", "Tata Nexon", "Mahindra XUV500",
    "Renault Kwid", "Toyota Fortuner", "Maruti Swift", "Kia Seltos",
    "Tata Tiago", "Maruti Baleno", "Hyundai Creta", "Hyundai i20",
    "Honda City", "Hyundai Grand i10", "Hyundai i10", "Mahindra Scorpio",
    "Skoda Rapid", "Ford EcoSport", "Tata Punch", "Maruti Dzire",
    "Honda Amaze", "Maruti Alto", "Hyundai Verna", "Volkswagen Polo"
]

# ---------------- INPUT FORM ----------------
with st.form("car_details"):
    st.subheader("Enter car details")

    c1, c2 = st.columns(2)
    with c1:
        car_name = st.selectbox("Car model", car_names)
        year = st.number_input("Manufacturing year", min_value=1990, max_value=2026, value=2020, step=1)
        km_driven = st.number_input("Kilometres driven", min_value=0, max_value=1_000_000, value=45000, step=1000)
        fuel = st.selectbox("Fuel type", ["Petrol", "Diesel", "CNG"])
    with c2:
        seller_type = st.selectbox("Seller type", ["Individual", "Dealer", "Trustmark Dealer"])
        transmission = st.selectbox("Transmission", ["Manual", "Automatic"])
        owner = st.selectbox("Ownership", ["First Owner", "Second Owner", "Third Owner", "Fourth & Above Owner"])

    submitted = st.form_submit_button("✨ Predict Car Price")

# ---------------- PREDICTION ----------------
if submitted:
    car_input = pd.DataFrame([{
        "name": car_name,
        "year": int(year),
        "km_driven": int(km_driven),
        "fuel": fuel,
        "seller_type": seller_type,
        "transmission": transmission,
        "owner": owner
    }])

    try:
        predicted_price = float(model.predict(car_input)[0])
        predicted_price = max(0, predicted_price)

        st.markdown("---")
        st.subheader("Your estimated resale value")
        st.markdown(
            f"""
            <div class="result">
              <div class="result-label">Predicted car price</div>
              <div class="result-price">₹ {predicted_price:,.0f}</div>
              <div class="result-label">Estimated value • Indian Rupees (INR)</div>
            </div>
            """,
            unsafe_allow_html=True
        )
        st.info("This is a machine-learning estimate based on the dataset used to train the model, not a guaranteed selling price.")
    except Exception as e:
        st.error(f"Prediction failed: {e}")

st.markdown("---")
st.caption("CarValue • Academic Machine Learning Project")
